// Records the output of every browser-runnable snippet into web/outputs.js.
// The app shows these when live Python is unavailable (offline, or a host that can't load packages).
// Usage: node tools/record_outputs.js
const fs = require("fs"), path = require("path"), { spawnSync } = require("child_process");
global.window = {};
eval(fs.readFileSync(path.join(__dirname, "../web/content.js"), "utf8"));
const out = {};
for (const t of window.TRACKS) t.steps.forEach((s, i) => {
  if (s.run === false) return;
  const code = s.code.replace(/^await (.+?)(\s+#.*)?$/gm, "import asyncio; asyncio.run($1)");
  const r = spawnSync("python3", ["-c", code], { encoding: "utf8", timeout: 60000 });
  if (r.status !== 0) throw new Error(`${t.id}-${i + 1} failed:\n${r.stderr}`);
  out[`${t.id}-${i + 1}`] = (r.stdout + r.stderr).trimEnd();
});
fs.writeFileSync(path.join(__dirname, "../web/outputs.js"),
  "// Generated by tools/record_outputs.js. Do not edit by hand.\nwindow.OUTPUTS = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`recorded ${Object.keys(out).length} outputs`);
